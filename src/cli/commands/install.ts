import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

import { createRepositoryContext } from "../../core/index.ts";
import { printJson, requireFlag } from "../commandSupport.ts";
import type { CliCommandHandler } from "../types.ts";

type InstallResult = {
  /** Absolute external memory repository root. */
  memoryRootDir: string;
  /** Absolute tool repository root that received local config files. */
  toolRootDir: string;
  /** Indicates whether a git repository was initialized during installation. */
  gitInitialized: boolean;
  /** Relative directories created inside the memory repository. */
  created: string[];
  /** Optional project slug bootstrapped during installation. */
  project?: string;
  /** Absolute local shell env file generated for the tool repository. */
  envFilePath: string;
  /** Absolute local Codex MCP config snippet generated for the tool repository. */
  codexConfigPath: string;
  /** Absolute global Codex config file updated during installation. */
  codexGlobalConfigPath: string;
  /** Indicates whether global Codex registration was requested. */
  codexGlobalConfigUpdated: boolean;
  /** Absolute local Claude MCP config snippet generated for the tool repository. */
  claudeConfigPath: string;
  /** Absolute global Claude config file updated during installation. */
  claudeGlobalConfigPath: string;
  /** Indicates whether global Claude registration was requested. */
  claudeGlobalConfigUpdated: boolean;
  /** Exact follow-up commands for the operator. */
  nextSteps: string[];
};

const codexServerSectionHeader = "[mcp_servers.project-memory]";
const codexEnvSectionHeader = "[mcp_servers.project-memory.env]";

type ClaudeMcpServerConfig = {
  type: "stdio";
  command: string;
  args: string[];
  env: Record<string, string>;
};

/**
 * Escapes one string value for TOML basic-string usage.
 */
const escapeTomlString = (value: string): string => {
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
};

/**
 * Escapes one string value for POSIX shell single-quoted usage.
 */
const escapeShellString = (value: string): string => {
  return `'${value.replaceAll("'", `'\\''`)}'`;
};

/**
 * Returns `true` when a value is a plain object.
 */
const isRecord = (value: unknown): value is Record<string, unknown> => {
  return typeof value === "object" && value !== null && !Array.isArray(value);
};

/**
 * Builds the canonical Codex MCP configuration block for this installation.
 */
const createCodexConfigBlock = (toolRootDir: string, memoryRootDir: string): string => {
  const mcpServerEntryPoint = path.join(toolRootDir, "src", "mcp", "server.ts");

  return [
    "# Auto-generated by project-memory install",
    codexServerSectionHeader,
    'command = "node"',
    `args = ["--experimental-strip-types", "${escapeTomlString(mcpServerEntryPoint)}"]`,
    `cwd = "${escapeTomlString(toolRootDir)}"`,
    "",
    codexEnvSectionHeader,
    `PROJECT_MEMORY_ROOT = "${escapeTomlString(memoryRootDir)}"`,
    "",
  ].join("\n");
};

/**
 * Builds the canonical Claude MCP configuration entry for this installation.
 */
const createClaudeServerConfig = (
  toolRootDir: string,
  memoryRootDir: string,
): ClaudeMcpServerConfig => {
  const mcpServerEntryPoint = path.join(toolRootDir, "src", "mcp", "server.ts");

  return {
    type: "stdio",
    command: "node",
    args: ["--experimental-strip-types", mcpServerEntryPoint],
    env: {
      PROJECT_MEMORY_ROOT: memoryRootDir,
    },
  };
};

/**
 * Replaces one known MCP server block in a TOML file without touching other sections.
 */
const upsertCodexConfigBlock = (configContents: string, block: string): string => {
  const lines = configContents === "" ? [] : configContents.split("\n");
  const start = lines.findIndex((line) => line.trim() === codexServerSectionHeader);

  if (start === -1) {
    const trimmedConfig = configContents.trim();
    return trimmedConfig === "" ? block : `${trimmedConfig}\n\n${block}`;
  }

  let end = lines.length;

  for (let index = start + 1; index < lines.length; index += 1) {
    const trimmedLine = lines[index].trim();
    if (!trimmedLine.startsWith("[") || !trimmedLine.endsWith("]")) {
      continue;
    }

    if (trimmedLine === codexEnvSectionHeader) {
      continue;
    }

    end = index;
    break;
  }

  const replacementLines = block.trimEnd().split("\n");
  const updatedLines = [...lines.slice(0, start), ...replacementLines, ...lines.slice(end)];

  return `${updatedLines.join("\n").replace(/\n*$/, "")}\n`;
};

/**
 * Writes one local shell env file for this tool installation.
 */
const writeLocalEnvFile = (toolRootDir: string, memoryRootDir: string): string => {
  const envFilePath = path.join(toolRootDir, ".project-memory.env");
  const envFileContents = [
    "# Auto-generated by project-memory install",
    `export PROJECT_MEMORY_ROOT=${escapeShellString(memoryRootDir)}`,
    "",
  ].join("\n");

  fs.writeFileSync(envFilePath, envFileContents, "utf8");
  return envFilePath;
};

/**
 * Writes one Codex MCP config snippet for this tool installation.
 */
const writeLocalCodexConfigFile = (toolRootDir: string, memoryRootDir: string): string => {
  const codexConfigPath = path.join(toolRootDir, ".project-memory.codex.toml");
  const codexConfig = createCodexConfigBlock(toolRootDir, memoryRootDir);

  fs.writeFileSync(codexConfigPath, codexConfig, "utf8");
  return codexConfigPath;
};

/**
 * Updates the global Codex config with this installation's MCP server registration.
 */
const writeGlobalCodexConfigFile = (toolRootDir: string, memoryRootDir: string): string => {
  const codexConfigPath = path.join(os.homedir(), ".codex", "config.toml");
  const existingConfig = fs.existsSync(codexConfigPath)
    ? fs.readFileSync(codexConfigPath, "utf8")
    : "";
  const codexConfig = upsertCodexConfigBlock(
    existingConfig,
    createCodexConfigBlock(toolRootDir, memoryRootDir),
  );

  fs.mkdirSync(path.dirname(codexConfigPath), { recursive: true });
  fs.writeFileSync(codexConfigPath, codexConfig, "utf8");
  return codexConfigPath;
};

/**
 * Updates the global Claude config with this installation's MCP server registration.
 */
const writeGlobalClaudeConfigFile = (toolRootDir: string, memoryRootDir: string): string => {
  const claudeConfigPath = path.join(os.homedir(), ".claude.json");
  const claudeServerConfig = createClaudeServerConfig(toolRootDir, memoryRootDir);
  const existingConfig = fs.existsSync(claudeConfigPath)
    ? fs.readFileSync(claudeConfigPath, "utf8")
    : "";
  let parsedConfig: Record<string, unknown>;

  if (existingConfig.trim() === "") {
    parsedConfig = {};
  } else {
    const parsedValue: unknown = JSON.parse(existingConfig);
    if (!isRecord(parsedValue)) {
      throw new Error("Global Claude config must be a JSON object");
    }

    parsedConfig = parsedValue;
  }

  const mcpServers = isRecord(parsedConfig.mcpServers) ? { ...parsedConfig.mcpServers } : {};
  mcpServers["project-memory"] = claudeServerConfig;

  const updatedConfig = {
    ...parsedConfig,
    mcpServers,
  };

  fs.writeFileSync(claudeConfigPath, `${JSON.stringify(updatedConfig, null, 2)}\n`, "utf8");
  return claudeConfigPath;
};

/**
 * Writes one Claude MCP config snippet for this tool installation.
 */
const writeLocalClaudeConfigFile = (toolRootDir: string, memoryRootDir: string): string => {
  const claudeConfigPath = path.join(toolRootDir, ".project-memory.claude.mcp.json");
  const claudeConfig = {
    mcpServers: {
      "project-memory": createClaudeServerConfig(toolRootDir, memoryRootDir),
    },
  };

  fs.writeFileSync(claudeConfigPath, `${JSON.stringify(claudeConfig, null, 2)}\n`, "utf8");
  return claudeConfigPath;
};

/**
 * Converts an arbitrary label into a filesystem-safe project slug.
 */
const slugifyProject = (project: string): string => {
  const slug = project
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  if (!slug) {
    throw new Error("Project must not be empty");
  }

  return slug;
};

/**
 * Parses one optional boolean CLI flag.
 */
const parseBooleanFlag = (value: string | undefined, fallback: boolean): boolean => {
  if (value === undefined) {
    return fallback;
  }

  if (value === "true") {
    return true;
  }

  if (value === "false") {
    return false;
  }

  throw new Error(`Boolean flags must use true or false, received: ${value}`);
};

/**
 * Initializes a git repository at the given memory root when requested.
 */
const ensureGitRepository = (memoryRootDir: string, shouldInitializeGit: boolean): boolean => {
  if (!shouldInitializeGit || fs.existsSync(path.join(memoryRootDir, ".git"))) {
    return false;
  }

  const initResult = spawnSync("git", ["init", "-q"], {
    cwd: memoryRootDir,
    encoding: "utf8",
  });

  if (initResult.status !== 0) {
    const stderr = initResult.stderr.trim();
    const stdout = initResult.stdout.trim();
    throw new Error(stderr || stdout || "git init failed");
  }

  return true;
};

/**
 * Returns `true` when `candidatePath` is the same path as `parentPath` or is nested under it.
 */
const isSameOrNestedPath = (candidatePath: string, parentPath: string): boolean => {
  const relativePath = path.relative(parentPath, candidatePath);
  return relativePath === "" || (!relativePath.startsWith("..") && !path.isAbsolute(relativePath));
};

/**
 * Rejects memory-root values that are not external to the tool repository.
 */
const validateExternalMemoryRoot = (memoryRootDir: string, toolRootDir: string): void => {
  if (
    isSameOrNestedPath(memoryRootDir, toolRootDir) ||
    isSameOrNestedPath(toolRootDir, memoryRootDir)
  ) {
    throw new Error(
      "Memory root must point to an external repository that does not overlap the tool repository.",
    );
  }
};

/**
 * Creates the base memory-repository layout and optionally one project tree.
 */
const installMemoryRepository = (
  memoryRootInput: string,
  project: string | undefined,
  shouldInitializeGit: boolean,
  shouldUpdateCodexGlobalConfig: boolean,
  shouldUpdateClaudeGlobalConfig: boolean,
  toolRootDir: string | undefined,
): InstallResult => {
  const memoryRootDir = path.resolve(memoryRootInput);
  const created = new Set<string>();
  const context = createRepositoryContext({ memoryRootDir, toolRootDir });
  validateExternalMemoryRoot(context.memoryRootDir, context.toolRootDir);

  for (const directoryName of ["projects", "archives"]) {
    const absolutePath = path.join(memoryRootDir, directoryName);
    fs.mkdirSync(absolutePath, { recursive: true });
    created.add(directoryName);
  }

  const gitInitialized = ensureGitRepository(memoryRootDir, shouldInitializeGit);
  let projectSlug: string | undefined;

  if (project) {
    projectSlug = slugifyProject(project);
    const year = new Date().toISOString().slice(0, 4);
    const projectDirectories = [
      path.join(context.projectsDir, projectSlug, "canonical-docs"),
      path.join(context.projectsDir, projectSlug, "decisions", year),
      path.join(context.projectsDir, projectSlug, "provider-notes"),
      path.join(context.projectsDir, projectSlug, "runbooks"),
      path.join(context.projectsDir, projectSlug, "session-log"),
      path.join(context.projectsDir, projectSlug, "verification"),
      path.join(context.archivesDir, projectSlug, "session-log"),
      path.join(context.archivesDir, projectSlug, "verification"),
    ];

    for (const directory of projectDirectories) {
      fs.mkdirSync(directory, { recursive: true });
      created.add(path.relative(memoryRootDir, directory));
    }
  }

  const envFilePath = writeLocalEnvFile(context.toolRootDir, memoryRootDir);
  const codexConfigPath = writeLocalCodexConfigFile(context.toolRootDir, memoryRootDir);
  const codexGlobalConfigPath = shouldUpdateCodexGlobalConfig
    ? writeGlobalCodexConfigFile(context.toolRootDir, memoryRootDir)
    : path.join(os.homedir(), ".codex", "config.toml");
  const claudeConfigPath = writeLocalClaudeConfigFile(context.toolRootDir, memoryRootDir);
  const claudeGlobalConfigPath = shouldUpdateClaudeGlobalConfig
    ? writeGlobalClaudeConfigFile(context.toolRootDir, memoryRootDir)
    : path.join(os.homedir(), ".claude.json");

  return {
    memoryRootDir,
    toolRootDir: context.toolRootDir,
    gitInitialized,
    created: [...created].sort(),
    project: projectSlug,
    envFilePath,
    codexConfigPath,
    codexGlobalConfigPath,
    codexGlobalConfigUpdated: shouldUpdateCodexGlobalConfig,
    claudeConfigPath,
    claudeGlobalConfigPath,
    claudeGlobalConfigUpdated: shouldUpdateClaudeGlobalConfig,
    nextSteps: [
      shouldUpdateCodexGlobalConfig
        ? `grep -n "mcp_servers.project-memory" ${escapeShellString(codexGlobalConfigPath)}`
        : `cat ${escapeShellString(codexConfigPath)}`,
      shouldUpdateClaudeGlobalConfig
        ? `grep -n '"project-memory"' ${escapeShellString(claudeGlobalConfigPath)}`
        : `cat ${escapeShellString(claudeConfigPath)}`,
      projectSlug
        ? `${escapeShellString(path.join(context.toolRootDir, "scripts", "run-cli.sh"))} list-documents --project ${projectSlug}`
        : `${escapeShellString(path.join(context.toolRootDir, "scripts", "run-cli.sh"))} bootstrap --project <project-slug>`,
    ],
  };
};

/**
 * Handles the `install` CLI command.
 */
export const installCommand: CliCommandHandler = (flags, io) => {
  const result = installMemoryRepository(
    requireFlag(flags, "memory-root"),
    flags.project,
    parseBooleanFlag(flags["git-init"], true),
    parseBooleanFlag(flags["codex-global"], true),
    parseBooleanFlag(flags["claude-global"], true),
    io.context?.toolRootDir,
  );

  printJson(result, io);
};
